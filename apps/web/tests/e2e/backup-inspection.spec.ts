import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('inspect a real encrypted fixture backup without restoring current data', async ({ page }) => {
  await page.goto('/?view=settings');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await page.locator('summary').getByText('גיבוי ושחזור',{exact:true}).click();
  await expect(page.getByRole('heading', { name: 'גיבוי וייצוא', exact: true })).toBeVisible();
  const session = await (await page.request.get('/api/session')).json(); expect(session.test_mode).toBe(true);
  const headers = { Origin: BASE, 'X-CSRF-Token': session.csrf };
  const task = await (await page.request.post('/api/tasks', { headers, data: { title: 'Inspection browser fixture' } })).json();
  const password = 'browser inspection fixture password';
  expect((await page.request.post('/api/recovery/backups', { headers, data: { password } })).status()).toBe(201);
  await page.reload();
  await page.locator('summary').getByText('גיבוי ושחזור',{exact:true}).click();
  await page.getByRole('button', { name: 'בדיקת תקינות', exact: true }).first().click();
  const dialog = page.getByRole('dialog', { name: 'בדיקת גיבוי מוצפן', exact: true });
  await dialog.getByLabel('סיסמת הגיבוי לבדיקה', { exact: true }).fill('wrong browser fixture password');
  await dialog.getByRole('button', { name: 'בדיקת הגיבוי ללא שחזור', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('לא ניתן לאמת את הגיבוי');
  await expect(dialog.getByLabel('סיסמת הגיבוי לבדיקה', { exact: true })).toHaveValue('');
  await dialog.getByLabel('סיסמת הגיבוי לבדיקה', { exact: true }).fill(password);
  await dialog.getByRole('button', { name: 'בדיקת הגיבוי ללא שחזור', exact: true }).click();
  await expect(dialog.getByText('הגיבוי עבר את בדיקות התקינות.', { exact: true })).toBeVisible();
  expect(await (await page.request.get('/api/tasks')).json()).toEqual([task]);
  await expect(dialog.getByText('Inspection browser fixture', { exact: false })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../../.runtime/screenshots/backup-inspection-mobile.png', fullPage: true });
  await dialog.getByRole('button', { name: 'סגירה', exact: true }).click();
  const settings = await (await page.request.get('/api/settings')).json();
  await page.request.put('/api/settings', { headers, data: { ...settings, language: 'en', theme: 'light' } });
  await page.reload();
  await page.locator('summary').getByText('Backup and restore',{exact:true}).click();
  await page.getByRole('button', { name: 'Check integrity', exact: true }).first().click();
  await expect(page.getByRole('dialog', { name: 'Inspect encrypted backup', exact: true })).toBeVisible();
  await page.getByLabel('Password for backup inspection', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Check backup without restoring', exact: true }).click();
  await expect(page.getByText('Backup integrity checks passed.', { exact: true })).toBeVisible();
});
