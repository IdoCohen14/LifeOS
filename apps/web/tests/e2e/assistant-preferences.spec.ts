import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';

test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('assistant preference consent is independent and source details stay out of chat context', async ({ page }) => {
  await page.goto('/?view=settings');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await page.locator('summary').getByText('העדפות תכנון',{exact:true}).click();
  await page.getByText('הצגה ועריכת העדפות', { exact: true }).click();
  const assistantOptIn = page.getByLabel('שימוש בהעדפות במציאת זמן פנוי בעוזר', { exact: true });
  await expect(assistantOptIn).not.toBeChecked();
  await assistantOptIn.check();
  await page.getByLabel('משך מועדף בדקות').fill('90');
  await page.getByLabel('שעת התחלה מועדפת').fill('09:30');
  await page.getByLabel('שעת סיום מועדפת').fill('17:00');
  const weekdays=page.getByRole('group',{name:'ימי תכנון',exact:true});
  for(const label of ['ראשון','שלישי','חמישי','שישי','שבת']) await weekdays.getByLabel(label,{exact:true}).uncheck();
  await page.getByRole('button', { name: 'שמירת העדפות', exact: true }).click();
  await expect(page.getByText('ההעדפות נשמרו.', { exact: false })).toBeVisible();
  const session = await (await page.request.get('/api/session')).json();
  expect(session.test_mode).toBe(true);
  const saved = await (await page.request.get('/api/planning/preferences')).json();
  expect(saved.assistant_enabled).toBe(true); expect(saved.enabled).toBe(false);
  await page.reload();
  await page.locator('summary').getByText('העדפות תכנון',{exact:true}).click();
  await page.getByText('הצגה ועריכת העדפות', { exact: true }).click();
  await expect(assistantOptIn).toBeChecked();
  await expect(page.getByLabel('שימוש בהעדפות בתכנון משימה', { exact: true })).not.toBeChecked();
  await page.route('**/api/assistant/status', route => route.fulfill({ json: { ready: true, model: 'fixture-only', local: true, state: 'ready' } }));
  const sent: { history: unknown }[] = [];
  await page.route('**/api/assistant/chat', async route => {
    sent.push(route.request().postDataJSON());
    await route.fulfill({ json: { reply: 'בדוק את הפרטים ואשר שמירה.', proposal: sent.length > 1 ? null : { id: '00000000-0000-0000-0000-000000000001', kind: 'event', payload: { title: 'Preference fixture', start: '2026-10-28T07:30:00Z', end: '2026-10-28T09:00:00Z' }, preference_source: { weekdays: saved.weekdays, window_start: saved.window_start, window_end: saved.window_end, default_duration: saved.duration } } } });
  });
  await page.getByRole('button', { name: 'העוזר האישי', exact: true }).click();
  await page.getByLabel('הודעה לעוזר', { exact: true }).fill('מצא לי זמן פנוי מחר');
  await page.getByRole('button', { name: 'שליחת הודעה', exact: true }).click();
  await expect(page.getByText('מבוסס על העדפות ששמרת', { exact: false })).toContainText('09:30–17:00');
  await expect(page.getByText('מבוסס על העדפות ששמרת',{exact:false})).toContainText('שני, רביעי');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('dialog').screenshot({ path: '../../.runtime/screenshots/assistant-preferences-mobile.png' });
  await page.getByLabel('הודעה לעוזר', { exact: true }).fill('אפשר להמשיך');
  await page.getByRole('button', { name: 'שליחת הודעה', exact: true }).click();
  await expect.poll(() => sent.length).toBe(2);
  const context = JSON.stringify(sent[1].history);
  expect(context).not.toContain('weekdays'); expect(context).not.toContain('09:30'); expect(context).not.toContain('17:00'); expect(context).not.toContain('2026-10-28T07:30');
  await page.getByRole('button', { name: 'סגירה', exact: true }).click();
  expect((await page.request.put('/api/settings', { headers: { Origin: BASE, 'X-CSRF-Token': session.csrf }, data: { language: 'en', theme: 'light', timezone: 'Asia/Jerusalem' } })).ok()).toBe(true);
  await page.reload();
  await page.locator('summary').getByText('Planning preferences',{exact:true}).click();
  await page.getByText('View and edit preferences', { exact: true }).click();
  await expect(page.getByLabel('Use preferences for assistant free-slot requests', { exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Reset preferences', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm preference reset', exact: true }).click();
  await expect(page.getByLabel('Use preferences for assistant free-slot requests', { exact: true })).not.toBeChecked();
  expect((await (await page.request.get('/api/planning/preferences')).json()).assistant_enabled).toBe(false);
  expect((await(await page.request.get('/api/planning/preferences')).json()).weekdays).toEqual([1,2,3,4,5,6,7]);
  expect(await (await page.request.get('/api/events')).json()).toEqual([]);
});
