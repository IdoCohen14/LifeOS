import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('built-in help works with no model and preserves the unsent chat draft', async ({ page }) => {
  let chatCalls=0;
  await page.route('**/api/assistant/status',route=>route.fulfill({json:{ready:false,local:true,state:'runtime_unavailable',model:'fixture-only'}}));
  await page.route('**/api/assistant/chat',route=>{chatCalls++;return route.fulfill({status:503,json:{detail:'fixture inference must not run'}});});
  await page.goto('/');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button',{name:'כניסה למרחב שלך'}).click();
  await page.getByRole('button',{name:'העוזר האישי',exact:true}).click();
  await page.getByLabel('הודעה לעוזר',{exact:true}).fill('טיוטת תכנון שטרם נשלחה');
  await expect(page.getByRole('button',{name:'שליחת הודעה',exact:true})).toBeDisabled();
  await page.getByText('עזרה מובנית באפליקציה',{exact:true}).click();
  await page.getByLabel('נושא לעזרה',{exact:true}).selectOption('backups');
  await expect(page.locator('.help-answer')).toContainText('גיבוי ושחזור');
  await page.getByLabel('נושא לעזרה',{exact:true}).selectOption('recurrence');
  await expect(page.locator('.help-answer')).toContainText('ניהול סדרות שבועיות');
  await expect(page.getByLabel('הודעה לעוזר',{exact:true})).toHaveValue('טיוטת תכנון שטרם נשלחה');
  expect(chatCalls).toBe(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../../.runtime/screenshots/built-in-help-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'סגירה',exact:true}).click();
  const session=await (await page.request.get('/api/session')).json();expect(session.test_mode).toBe(true);
  const settings=await (await page.request.get('/api/settings')).json();
  await page.request.put('/api/settings',{headers:{Origin:BASE,'X-CSRF-Token':session.csrf},data:{...settings,language:'en',theme:'light'}});
  await page.reload();
  await page.getByRole('button',{name:'Open assistant',exact:true}).click();
  await page.getByText('Built-in app help',{exact:true}).click();
  await page.getByLabel('Help topic',{exact:true}).selectOption('planning');
  await expect(page.locator('.help-answer')).toContainText('Make time for tasks');
  expect(chatCalls).toBe(0);
});
