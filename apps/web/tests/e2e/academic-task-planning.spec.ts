import { test, expect } from "@playwright/test";
import { BASE, prepareFixtures } from "./helpers";
import { dayKey, shiftDay } from "../../lib/dates";
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));

test("an academic deadline opens its real task for reviewed time allocation", async ({ page }) => {
  await page.goto("/?view=academic");
  await page.getByLabel("הסיסמה שלך").fill("lifeos automated test password");
  await page.getByRole("button", {name:"כניסה למרחב שלך"}).click();
  await expect(page.locator("#page-title")).toBeVisible();
  const session = await (await page.request.get("/api/session")).json();
  expect(session.test_mode).toBe(true);
  const headers = {Origin:BASE,"X-CSRF-Token":session.csrf};
  async function create(kind:string,data:object) {
    const response=await page.request.post(`/api/academic/${kind}`,{headers,data});
    expect(response.ok()).toBe(true);return response.json();
  }
  const today=dayKey(new Date(),"Asia/Jerusalem"), tomorrow=shiftDay(today,1);
  const term=await create("terms",{name:"Planning term fixture",start_date:today,end_date:shiftDay(today,90)});
  const course=await create("courses",{name:"Planning course fixture",term_id:term.id});
  const item=await create("items",{title:"Academic planning fixture",course_id:course.id,kind:"assignment",due:shiftDay(today,3)});
  await page.reload();
  const region=page.getByRole("region",{name:"מטלות ומבחנים",exact:true});
  await region.locator(".item-extra > summary").first().click();
  await region.getByRole("button",{name:`הקצאת זמן: ${item.title}`}).click();
  const dialog=page.getByRole("dialog",{name:"תכנון זמן למשימה"});
  await expect(dialog.getByLabel("משימה לתכנון",{exact:true})).toHaveValue(item.task_id);
  await dialog.getByLabel("מתאריך",{exact:true}).fill(tomorrow);
  await dialog.getByLabel("משך בדקות",{exact:true}).fill("45");
  await dialog.getByRole("button",{name:"הצעת זמן",exact:true}).click();
  expect(await (await page.request.get("/api/events")).json()).toHaveLength(0);
  await page.setViewportSize({width:320,height:740});
  expect(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
  await dialog.getByRole("button",{name:"אישור ושמירה ביומן",exact:true}).click();
  await expect(dialog.getByText("נשמר ביומן. המשימה נשארת פתוחה.",{exact:true})).toBeVisible();
  const tasks=await (await page.request.get("/api/tasks")).json();
  expect(tasks.find((task:{id:string})=>task.id===item.task_id)).toMatchObject({completed:false,due:item.due});
  const events=await (await page.request.get("/api/events")).json();
  expect(events).toHaveLength(1);
  expect(Date.parse(events[0].end)-Date.parse(events[0].start)).toBe(45*60000);
  await dialog.getByRole("button",{name:"פתיחה ביומן",exact:true}).click();
  await expect(page).toHaveURL(new RegExp(`view=calendar&day=${tomorrow}`));
  await page.goto(`/?view=academic&course=${course.id}`);
  await page.locator(".course-panel .item-extra > summary").first().click();
  await page.getByRole("button",{name:`הקצאת זמן: ${item.title}`}).click();
  await expect(dialog.getByText("כבר מוקצה למשימה זמן עתידי ביומן.",{exact:true})).toHaveCount(0);
  await dialog.getByLabel("מתאריך",{exact:true}).fill(tomorrow);
  await dialog.getByRole("button",{name:"הצעת זמן",exact:true}).click();
  await expect(dialog.getByText("כבר מוקצה למשימה זמן עתידי ביומן.",{exact:true})).toBeVisible();
  await expect(dialog.getByRole("button",{name:"אישור ושמירה ביומן",exact:true})).toHaveCount(0);
  await dialog.getByRole("button",{name:"סגירה",exact:true}).click();
  await page.getByLabel("להציג גם פריטים שהושלמו",{exact:true}).check();
  await page.getByRole("checkbox",{name:`השלמה: ${item.title}`}).click();
  await expect(page.getByRole("button",{name:`הקצאת זמן: ${item.title}`})).toHaveCount(0);
  await page.getByRole("checkbox",{name:`השלמה: ${item.title}`}).click();
  await expect(page.getByRole("button",{name:`הקצאת זמן: ${item.title}`})).toBeVisible();
  const settings=await (await page.request.get("/api/settings")).json();
  expect((await page.request.put("/api/settings",{headers,data:{...settings,language:"en",theme:"light"}})).ok()).toBe(true);
  await page.goto("/?view=academic");
  await page.locator(".academic-deadlines .item-extra > summary").first().click();
  await page.getByRole("button",{name:`Plan time: ${item.title}`}).click();
  const english=page.getByRole("dialog",{name:"Plan time for a task"});
  await expect(english.getByLabel("Task to plan",{exact:true})).toHaveValue(item.task_id);
  await english.getByLabel("Starting date",{exact:true}).fill(tomorrow);
  await english.getByRole("button",{name:"Suggest a time",exact:true}).click();
  await expect(english.getByText("This task already has a future calendar block.",{exact:true})).toBeVisible();
});
