import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';
import { dayKey, shiftDay } from '../../lib/dates';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('series deletion protects individual edits and reviews full edited all-day range', async ({ page }) => {
  await page.goto('/?view=calendar');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await expect(page.getByRole('button', { name: 'ניהול סדרות שבועיות', exact: true })).toBeVisible();
  const session=await (await page.request.get('/api/session')).json(); expect(session.test_mode).toBe(true);
  const headers={Origin:BASE,'X-CSRF-Token':session.csrf};
  const first=shiftDay(dayKey(new Date(),'Asia/Jerusalem'),1);
  const preview=await (await page.request.post('/api/recurrence/preview',{headers,data:{title:'Managed browser weekly fixture',day:first,count:3,clock:'09:00',duration:60,all_day:false,timezone:'Asia/Jerusalem'}})).json();
  expect((await page.request.post('/api/recurrence/confirm',{headers,data:{id:preview.id}})).ok()).toBe(true);
  const events=await (await page.request.get('/api/events')).json();
  const unrelated=await (await page.request.post('/api/events',{headers,data:events[0]})).json();
  const multiStart=shiftDay(first,7), multiEnd=shiftDay(multiStart,10);
  const edited=await (await page.request.put(`/api/events/${events[1].id}`,{headers,data:{...events[1],title:'Protected edited all-day fixture',all_day:true,start:multiStart,end:multiEnd}})).json();
  await page.reload();
  await page.getByRole('button', { name: 'ניהול סדרות שבועיות', exact: true }).click();
  let dialog=page.getByRole('dialog',{name:'ניהול סדרות שבועיות',exact:true});
  await dialog.getByRole('button',{name:'תצוגה מקדימה למחיקה',exact:true}).click();
  await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(2);
  await expect(dialog.getByText('1 מופעים שנערכו או שמצבם אינו ידוע לא נבחרו.',{exact:true})).toBeVisible();
  expect(await (await page.request.get('/api/events')).json()).toHaveLength(4);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../../.runtime/screenshots/series-management-mobile.png',fullPage:true});
  let releaseRefresh!: () => void;
  const refreshGate = new Promise<void>(resolve => { releaseRefresh = resolve; });
  await page.route('**/api/events', async route => { await refreshGate; await route.continue(); });
  await dialog.getByRole('button',{name:'אישור מחיקת 2 מופעים',exact:true}).click();
  await expect(dialog.getByText('נמחקו 2 מופעים שנבדקו.',{exact:true})).toBeVisible();
  expect((await (await page.request.get('/api/events')).json()).map((value:{id:string})=>value.id).sort()).toEqual([edited.id,unrelated.id].sort());
  await dialog.getByRole('button',{name:'סגירה',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  releaseRefresh();
  await page.unrouteAll({ behavior: 'wait' });
  await page.getByRole('button',{name:'ניהול סדרות שבועיות',exact:true}).click();
  dialog=page.getByRole('dialog',{name:'ניהול סדרות שבועיות',exact:true});
  await dialog.getByLabel('לכלול גם מופעים שנערכו או שמצב המקור שלהם אינו ידוע').check();
  await dialog.getByRole('button',{name:'תצוגה מקדימה למחיקה',exact:true}).click();
  await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(1);
  await expect(dialog.getByText(shiftDay(multiEnd,-1).split('-').reverse().join('/'),{exact:false})).toBeVisible();
  await dialog.getByRole('button',{name:'אישור מחיקת 1 מופעים',exact:true}).click();
  await expect(dialog.getByText('נמחקו 1 מופעים שנבדקו.',{exact:true})).toBeVisible();
  expect(await (await page.request.get('/api/events')).json()).toEqual([unrelated]);
  expect((await (await page.request.get('/api/recurrence/series')).json()).items).toEqual([]);
});
