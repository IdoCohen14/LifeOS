import { test, expect } from '@playwright/test';
import { Temporal } from '@js-temporal/polyfill';
import { BASE,prepareFixtures,openDashboardTool,openSettingsSection } from './helpers';
import { dayKey,shiftDay } from '../../lib/dates';
test.beforeEach(async({playwright})=>prepareFixtures(playwright));
test('preferred weekdays prefill and allow an explicit per-proposal override without changing saved choices',async({page})=>{
 await page.goto('/?view=settings');
 await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
 await page.getByRole('button',{name:'כניסה למרחב שלך'}).click();
 await openSettingsSection(page,'העדפות תכנון');
 await page.getByText('הצגה ועריכת העדפות',{exact:true}).click();
 const session=await(await page.request.get('/api/session')).json();expect(session.test_mode).toBe(true);
 const headers={Origin:BASE,'X-CSRF-Token':session.csrf};
 const wanted=Temporal.PlainDate.from(shiftDay(dayKey(new Date(),'Asia/Jerusalem'),1)).dayOfWeek;
 const labels=['','שני','שלישי','רביעי','חמישי','שישי','שבת','ראשון'];
 const group=page.getByRole('group',{name:'ימי תכנון',exact:true});
 for(let day=1;day<=7;day++) await group.getByLabel(labels[day],{exact:true}).setChecked(day===wanted);
 await page.getByLabel('שימוש בהעדפות בתכנון משימה',{exact:true}).check();
 await page.getByLabel('מספר ימי חיפוש מועדף',{exact:true}).fill('7');
 await page.getByRole('button',{name:'שמירת העדפות',exact:true}).click();
 await expect(page.getByText('ההעדפות נשמרו.',{exact:false})).toBeVisible();
 expect((await(await page.request.get('/api/planning/preferences')).json()).weekdays).toEqual([wanted]);
 expect((await page.request.post('/api/tasks',{headers,data:{title:'Weekday override fixture'}})).ok()).toBe(true);
 await page.goto('/');
 await openDashboardTool(page,'למצוא זמן למשימות');
 await page.getByRole('button',{name:'מציאת משבצת זמן',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'תכנון זמן למשימה',exact:true});
 const selection=dialog.getByRole('group',{name:'ימי תכנון',exact:true});
 await expect(selection.getByLabel(labels[wanted],{exact:true})).toBeChecked();
 const override=wanted%7+1;
 await selection.getByLabel(labels[wanted],{exact:true}).uncheck();
 await selection.getByLabel(labels[override],{exact:true}).check();
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await dialog.screenshot({path:'../../.runtime/screenshots/preferred-weekdays-mobile.png'});
 await dialog.getByRole('button',{name:'הצעת זמן',exact:true}).click();
 await dialog.getByRole('button',{name:'אישור ושמירה ביומן',exact:true}).click();
 await expect(dialog.getByText('נשמר ביומן. המשימה נשארת פתוחה.',{exact:true})).toBeVisible();
 const events=await(await page.request.get('/api/events')).json();
 expect(events).toHaveLength(1);
 expect(Temporal.Instant.from(events[0].start).toZonedDateTimeISO('Asia/Jerusalem').dayOfWeek).toBe(override);
 expect((await(await page.request.get('/api/planning/preferences')).json()).weekdays).toEqual([wanted]);
});
