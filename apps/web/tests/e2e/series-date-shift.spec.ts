import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';
import { dayKey, shiftDay } from '../../lib/dates';

test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('date shifts preserve clocks and protect edited weekly occurrences', async ({ page }) => {
  await page.goto('/?view=calendar');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await expect(page.getByRole('button', { name: 'ניהול סדרות שבועיות', exact: true })).toBeVisible();
  await expect(page.getByRole('button', {name:'ניהול סדרות שבועיות',exact:true})).toBeVisible();
  const session = await (await page.request.get('/api/session')).json(); expect(session.test_mode).toBe(true);
  const headers = { Origin: BASE, 'X-CSRF-Token': session.csrf };
  const first = shiftDay(dayKey(new Date(), 'Asia/Jerusalem'), 1);
  const created = await (await page.request.post('/api/recurrence/preview', { headers, data: { title: 'Date shift fixture', day: first, clock: '09:00', duration: 60, count: 3, timezone: 'Asia/Jerusalem' } })).json();
  expect((await page.request.post('/api/recurrence/confirm', { headers, data: { id: created.id } })).ok()).toBe(true);
  const initial = await (await page.request.get('/api/events')).json();
  const edited = await (await page.request.put(`/api/events/${initial[1].id}`, { headers, data: { ...initial[1], title: 'Protected date fixture', start: new Date(Date.parse(initial[1].start) + 2 * 3600000).toISOString(), end: new Date(Date.parse(initial[1].end) + 2.5 * 3600000).toISOString() } })).json();
  const before = await (await page.request.get('/api/events')).json();
  await page.reload();
  await page.getByRole('button', { name: 'ניהול סדרות שבועיות', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'ניהול סדרות שבועיות', exact: true });
  await dialog.getByLabel('פעולה בסדרה', { exact: true }).selectOption('shift');
  await dialog.getByLabel('מספר ימים להזזה', { exact: true }).fill('2');
  await expect(dialog.getByLabel('שעה חדשה למופעים', { exact: true })).toHaveCount(0);
  await dialog.getByRole('button', { name: 'תצוגה מקדימה להזזת תאריכים', exact: true }).click();
  await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(2);
  await expect(dialog.getByText('1 מופעים שנערכו או שמצבם אינו ידוע לא נבחרו.', { exact: true })).toBeVisible();
  expect(await (await page.request.get('/api/events')).json()).toEqual(before);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.screenshot({ path: '../../.runtime/screenshots/series-date-shift-mobile.png' });
  await dialog.getByRole('button', { name: 'אישור הזזת 2 מופעים', exact: true }).click();
  await expect(dialog.getByText('הוזזו 2 מופעים שנבדקו.', { exact: true })).toBeVisible();
  const after = await (await page.request.get('/api/events')).json();
  expect(after.find((row: {id: string}) => row.id === edited.id)).toEqual(edited);
  for (const row of after.filter((value: {id: string}) => value.id !== edited.id)) {
    const old = before.find((value: {id: string}) => value.id === row.id);
    expect(dayKey(new Date(row.start), 'Asia/Jerusalem')).toBe(shiftDay(dayKey(new Date(old.start), 'Asia/Jerusalem'), 2));
    expect(Date.parse(row.end) - Date.parse(row.start)).toBe(Date.parse(old.end) - Date.parse(old.start));
    expect(new Intl.DateTimeFormat('en', { timeZone: 'Asia/Jerusalem', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' }).format(new Date(row.start))).toBe('09:00');
  }
  await dialog.getByRole('button', { name: 'סגירה', exact: true }).click();
  expect((await page.request.put('/api/settings', { headers, data: { language: 'en', theme: 'light', timezone: 'Asia/Jerusalem' } })).ok()).toBe(true);
  await page.reload();
  await page.getByRole('button', { name: 'Manage weekly series', exact: true }).click();
  await page.getByLabel('Series action', { exact: true }).selectOption('shift');
  await expect(page.getByLabel('Calendar days to shift', { exact: true })).toHaveValue('1');
});


test('all-day date shifts require inclusion and review full inclusive ranges before approval', async ({ page }) => {
  await page.goto('/?view=calendar');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await expect(page.getByRole('button', {name:'ניהול סדרות שבועיות',exact:true})).toBeVisible();
  const session = await (await page.request.get('/api/session')).json(); expect(session.test_mode).toBe(true);
  const headers = {Origin: BASE, 'X-CSRF-Token': session.csrf};
  const first = shiftDay(dayKey(new Date(), 'Asia/Jerusalem'), 1);
  const created = await (await page.request.post('/api/recurrence/preview', {headers, data:{title:'All-day shift fixture',day:first,all_day:true,count:3,timezone:'Asia/Jerusalem'}})).json();
  expect((await page.request.post('/api/recurrence/confirm', {headers,data:{id:created.id}})).ok()).toBe(true);
  const rows = await (await page.request.get('/api/events')).json();
  const edited = rows[0];
  expect((await page.request.put(`/api/events/${edited.id}`, {headers,data:{...edited,end:shiftDay(edited.start,3)}})).ok()).toBe(true);
  const before = await (await page.request.get('/api/events')).json();
  await page.reload();
  await page.getByRole('button',{name:'ניהול סדרות שבועיות',exact:true}).click();
  const dialog = page.getByRole('dialog',{name:'ניהול סדרות שבועיות',exact:true});
  await dialog.getByLabel('פעולה בסדרה',{exact:true}).selectOption('shift');
  await expect(dialog.getByLabel('לכלול אירועי יום שלם',{exact:true})).not.toBeChecked();
  await dialog.getByRole('button',{name:'תצוגה מקדימה להזזת תאריכים',exact:true}).click();
  await expect(dialog.getByText('3 אירועי יום שלם נשארים ללא שינוי.',{exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'שינוי הבחירה',exact:true}).click();
  await dialog.getByLabel('לכלול אירועי יום שלם',{exact:true}).check();
  await dialog.getByLabel('מספר ימים להזזה',{exact:true}).fill('2');
  await dialog.getByRole('button',{name:'תצוגה מקדימה להזזת תאריכים',exact:true}).click();
  await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(2);
  await dialog.getByRole('button',{name:'שינוי הבחירה',exact:true}).click();
  await dialog.getByLabel('לכלול גם מופעים שנערכו או שמצב המקור שלהם אינו ידוע',{exact:true}).check();
  await dialog.getByRole('button',{name:'תצוגה מקדימה להזזת תאריכים',exact:true}).click();
  await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(3);
  const range = dialog.locator('.recurring-preview-list li').filter({hasText:edited.title}).first();
  const pretty=(day:string)=>day.split('-').reverse().join('/');
  await expect(range).toContainText(`${pretty(shiftDay(first,2))} — ${pretty(shiftDay(first,4))} (כולל) · יום שלם`);
  expect(await (await page.request.get('/api/events')).json()).toEqual(before);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await dialog.screenshot({path:'../../.runtime/screenshots/series-all-day-shift-mobile.png'});
  await dialog.getByRole('button',{name:'אישור הזזת 3 מופעים',exact:true}).click();
  await expect(dialog.getByText('הוזזו 3 מופעים שנבדקו.',{exact:true})).toBeVisible();
  const after=await (await page.request.get('/api/events')).json();
  for(const old of before) expect(after.find((row:{id:string})=>row.id===old.id)).toEqual({...old,start:shiftDay(old.start,2),end:shiftDay(old.end,2)});
  await dialog.getByRole('button',{name:'סגירה',exact:true}).click();
  expect((await page.request.put('/api/settings',{headers,data:{language:'en',theme:'light',timezone:'America/Los_Angeles'}})).ok()).toBe(true);
  await page.reload();
  await page.getByRole('button',{name:'Manage weekly series',exact:true}).click();
  await page.getByLabel('Series action',{exact:true}).selectOption('shift');
  await expect(page.getByLabel('Include all-day occurrences',{exact:true})).not.toBeChecked();
  await page.getByLabel('Include all-day occurrences',{exact:true}).check();
  await page.getByLabel('Include edited occurrences or those with unknown original state',{exact:true}).check();
  await page.getByRole('button',{name:'Preview date shift',exact:true}).click();
  await expect(page.getByText('New dates:').first()).toBeVisible();
  await expect(page.locator('.recurring-preview-list li').first()).toContainText(`${pretty(shiftDay(first,3))} — ${pretty(shiftDay(first,5))} (inclusive) · All day`);
});
