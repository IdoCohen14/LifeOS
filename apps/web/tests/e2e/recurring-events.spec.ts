import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures } from './helpers';
import { shiftDay } from '../../lib/dates';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('finite weekly preview creates nothing before confirmation and stays individually editable', async ({ page }) => {
  await page.goto('/?view=calendar');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await expect(page.getByRole('button', { name: 'אירוע שבועי חוזר', exact: true })).toBeVisible();
  const session = await (await page.request.get('/api/session')).json(); expect(session.test_mode).toBe(true);
  await page.getByRole('button', { name: 'אירוע שבועי חוזר', exact: true }).click();
  await page.getByLabel('כותרת האירוע החוזר').fill('Weekly browser fixture');
  const first = await page.getByLabel('תאריך ראשון', { exact: true }).inputValue();
  await page.getByLabel('מספר מופעים שבועיים').fill('3');
  await page.getByRole('button', { name: 'תצוגה מקדימה של המופעים', exact: true }).click();
  await expect(page.locator('.recurring-preview-list li')).toHaveCount(3);
  expect(await (await page.request.get('/api/events')).json()).toEqual([]);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../../.runtime/screenshots/recurring-events-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'אישור יצירת 3 אירועים', exact: true }).click();
  await expect(page.getByText('האירועים נוצרו ביומן האישי.', { exact: true })).toBeVisible();
  const events = await (await page.request.get('/api/events')).json(); expect(events).toHaveLength(3);
  expect(events.map((item: { start: string }) => item.start.slice(0, 10))).toEqual([first, shiftDay(first, 7), shiftDay(first, 14)]);
  await page.getByRole('button', { name: 'סגירה', exact: true }).click();
  await page.goto(`/?view=calendar&day=${first}`);
  await expect(page.getByRole('button', { name: 'עריכה: Weekly browser fixture', exact: true })).toBeVisible();
  expect((await page.request.delete(`/api/events/${events[0].id}`, { headers: { Origin: BASE, 'X-CSRF-Token': session.csrf } })).status()).toBe(204);
  expect(await (await page.request.get('/api/events')).json()).toHaveLength(2);
});
