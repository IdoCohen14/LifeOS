import { test, expect } from '@playwright/test';
import { prepareFixtures, openSettingsSection } from './helpers';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('automatic backups need explicit password and retention consent, and off removes credential', async ({ page }) => {
  await page.goto('/?view=settings');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await openSettingsSection(page,'גיבוי ושחזור');
  await page.getByText('גיבוי מוצפן יומי אוטומטי', { exact: true }).click();
  await expect(page.getByLabel('הפעלת גיבוי יומי מתוזמן')).not.toBeChecked();
  await page.getByLabel('הפעלת גיבוי יומי מתוזמן').check();
  await page.getByLabel('שעת הגיבוי היומי').fill('23:30');
  await page.getByLabel('כמות גיבויים אוטומטיים לשמירה').fill('3');
  const secret = 'scheduled browser fixture password';
  await page.getByLabel('סיסמה לגיבוי מתוזמן', { exact: true }).fill(secret);
  await page.getByLabel('אימות הסיסמה לגיבוי מתוזמן', { exact: true }).fill(secret);
  await page.getByLabel('בדקתי את מדיניות השמירה ואת השימוש בסיסמה המוצפנת.').check();
  await page.getByRole('button', { name: 'שמירת תזמון גיבוי', exact: true }).click();
  await expect(page.getByText('תזמון הגיבוי נשמר.', { exact: false })).toBeVisible();
  const saved = await (await page.request.get('/api/recovery/schedule')).json();
  expect(saved.enabled && saved.configured).toBe(true);
  expect(JSON.stringify(saved)).not.toContain(secret);
  await expect(page.getByLabel('סיסמה לגיבוי מתוזמן', { exact: true })).toHaveValue('');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('details.notification-preferences').filter({ has: page.getByText('גיבוי מוצפן יומי אוטומטי', { exact: true }) }).screenshot({ path: '../../.runtime/screenshots/scheduled-backup-mobile.png' });
  await page.getByLabel('הפעלת גיבוי יומי מתוזמן').uncheck();
  await page.getByLabel('בדקתי את מדיניות השמירה ואת השימוש בסיסמה המוצפנת.').check();
  await page.getByRole('button', { name: 'שמירת תזמון גיבוי', exact: true }).click();
  await expect.poll(async () => (await (await page.request.get('/api/recovery/schedule')).json()).configured).toBe(false);
});
