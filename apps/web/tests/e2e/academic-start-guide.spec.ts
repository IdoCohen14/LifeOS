import { test, expect } from "@playwright/test";
import { dayKey, shiftDay } from "../../lib/dates";
import { prepareFixtures } from "./helpers";
test.beforeEach(async({playwright})=>prepareFixtures(playwright));
test("personal academic setup goes from empty records to an explicitly approved time block",async({page})=>{
 await page.goto("/?view=academic");
 await page.getByLabel("הסיסמה שלך").fill("lifeos automated test password");
 await page.getByRole("button",{name:"כניסה למרחב שלך"}).click();
 const guide=page.getByRole("region",{name:"מתחילים לנהל את הלימודים",exact:true});
 await expect(guide.getByRole("button",{name:"הוספת קורס",exact:true})).toBeDisabled();
 expect((await (await page.request.get("/api/session")).json()).test_mode).toBe(true);
 const today=dayKey(new Date(),"Asia/Jerusalem"),tomorrow=shiftDay(today,1);
 await guide.getByRole("button",{name:"הוספת סמסטר",exact:true}).click();
 let dialog=page.getByRole("dialog");
 await dialog.getByLabel("שם הסמסטר",{exact:true}).fill("Personal setup term fixture");
 await dialog.getByLabel("תאריך התחלה",{exact:true}).fill(today);
 await dialog.getByLabel("תאריך סיום",{exact:true}).fill(shiftDay(today,90));
 await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(guide.getByRole("progressbar")).toHaveAttribute("value","1");
 await expect(guide.getByRole("button",{name:"הוספת סמסטר",exact:true})).toBeFocused();
 await guide.getByRole("button",{name:"הוספת קורס",exact:true}).click();
 await dialog.getByLabel("שם הקורס",{exact:true}).fill("Personal setup course fixture");
 await dialog.getByLabel("נקודות זכות",{exact:true}).fill("3");
 await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(guide.getByRole("progressbar")).toHaveAttribute("value","2");
 await expect(guide.getByRole("button",{name:"הוספת קורס",exact:true})).toBeFocused();
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await guide.screenshot({path:"../../.runtime/screenshots/academic-start-mobile.png"});
 await guide.getByRole("button",{name:"הוספת מטלה ראשונה",exact:true}).click();
 const courses=await (await page.request.get("/api/academic/courses")).json();
 await dialog.getByLabel("קורס",{exact:true}).selectOption(courses[0].id);
 await dialog.getByLabel("כותרת",{exact:true}).fill("First real workflow fixture");
 await dialog.getByLabel("מועד",{exact:true}).fill(shiftDay(today,3));
 await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await expect(guide.locator("details")).not.toHaveAttribute("open","");
  await expect(page.locator("#main-content")).toBeFocused();
 await page.reload();
 await expect(guide.getByText("3/3 הוגדרו",{exact:true})).toBeVisible();
 await page.locator(".academic-deadlines .item-extra > summary").first().click();
 await page.getByRole("button",{name:"הקצאת זמן: First real workflow fixture"}).click();
 dialog=page.getByRole("dialog");
 await dialog.getByLabel("מתאריך",{exact:true}).fill(tomorrow);
 await dialog.getByRole("button",{name:"הצעת זמן",exact:true}).click();
 expect(await (await page.request.get("/api/events")).json()).toHaveLength(0);
 await dialog.getByRole("button",{name:"אישור ושמירה ביומן",exact:true}).click();
 await expect(dialog.getByText("נשמר ביומן. המשימה נשארת פתוחה.",{exact:true})).toBeVisible();
 expect(await (await page.request.get("/api/tasks")).json()).toEqual([expect.objectContaining({title:"First real workflow fixture",due:shiftDay(today,3),completed:false})]);
 await dialog.getByRole("button",{name:"פתיחה ביומן",exact:true}).click();
 await expect(page).toHaveURL(new RegExp(`view=calendar&day=${tomorrow}`));
});
