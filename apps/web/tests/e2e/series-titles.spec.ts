import { test,expect } from '@playwright/test';
import { BASE,prepareFixtures } from './helpers';
import { dayKey,shiftDay } from '../../lib/dates';
test.beforeEach(async({playwright})=>prepareFixtures(playwright));
test('reviewed title changes preserve all-day ranges and protected notes with explicit approval',async({page})=>{
 await page.goto('/?view=calendar');
 await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
 await page.getByRole('button',{name:'כניסה למרחב שלך'}).click();
 await expect(page.getByRole('button',{name:'ניהול סדרות שבועיות',exact:true})).toBeVisible();
 const session=await(await page.request.get('/api/session')).json();expect(session.test_mode).toBe(true);
 const headers={Origin:BASE,'X-CSRF-Token':session.csrf};
 const created=await(await page.request.post('/api/recurrence/preview',{headers,data:{title:'Original title fixture',day:shiftDay(dayKey(new Date(),'Asia/Jerusalem'),1),count:3,all_day:true,timezone:'Asia/Jerusalem'}})).json();
 expect((await page.request.post('/api/recurrence/confirm',{headers,data:{id:created.id}})).ok()).toBe(true);
 const rows=await(await page.request.get('/api/events')).json();
 const protectedRow=await(await page.request.put(`/api/events/${rows[1].id}`,{headers,data:{...rows[1],notes:'Individually protected title fixture'}})).json();
 const before=await(await page.request.get('/api/events')).json();
 await page.reload();
 await page.getByRole('button',{name:'ניהול סדרות שבועיות',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'ניהול סדרות שבועיות',exact:true});
 await dialog.getByLabel('פעולה בסדרה',{exact:true}).selectOption('rename');
 await expect(dialog.getByLabel('כותרת חדשה למופעים שנבחרו',{exact:true})).toHaveValue('');
 await dialog.getByLabel('כותרת חדשה למופעים שנבחרו',{exact:true}).fill('פגישת תכנון מעודכנת');
 await expect(dialog.getByLabel('שעה חדשה למופעים',{exact:true})).toHaveCount(0);
 await dialog.getByRole('button',{name:'תצוגה מקדימה לשינוי כותרות',exact:true}).click();
 await expect(dialog.locator('.recurring-preview-list li')).toHaveCount(2);
 await expect(dialog.getByText('1 מופעים שנערכו או שמצבם אינו ידוע לא נבחרו.',{exact:true})).toBeVisible();
 expect(await(await page.request.get('/api/events')).json()).toEqual(before);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await dialog.screenshot({path:'../../.runtime/screenshots/series-titles-mobile.png'});
 await dialog.getByRole('button',{name:'אישור שינוי כותרות של 2 מופעים',exact:true}).click();
 await expect(dialog.getByText('עודכנו הכותרות של 2 מופעים שנבדקו.',{exact:true})).toBeVisible();
 const after=await(await page.request.get('/api/events')).json();
 for(const old of before) expect(after.find((row:{id:string})=>row.id===old.id)).toEqual(old.id===protectedRow.id?old:{...old,title:'פגישת תכנון מעודכנת'});
 await dialog.getByRole('button',{name:'סגירה',exact:true}).click();
 expect((await page.request.put('/api/settings',{headers,data:{language:'en',theme:'light',timezone:'Asia/Jerusalem'}})).ok()).toBe(true);
 await page.reload();
 await page.getByRole('button',{name:'Manage weekly series',exact:true}).click();
 await page.getByLabel('Series action',{exact:true}).selectOption('rename');
 await expect(page.getByLabel('New title for selected occurrences',{exact:true})).toHaveValue('');
 await expect(page.getByRole('combobox',{name:'Series to manage',exact:true})).toContainText('Original title fixture');
 await page.getByLabel('New title for selected occurrences',{exact:true}).fill('Next reviewed fixture');
 await page.getByRole('button',{name:'Preview title changes',exact:true}).click();
 await expect(page.getByText('New title:',{exact:false}).first()).toBeVisible();
 await page.getByRole('button',{name:'Change selection',exact:true}).click();
 expect(await(await page.request.get('/api/events')).json()).toEqual(after);
});
