import { test, expect } from "@playwright/test";
import { BASE, prepareFixtures } from "./helpers";
import { dayKey, shiftDay } from "../../lib/dates";
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test("overview quick capture explicitly chooses a course within the selected term", async ({ page }) => {
  await page.goto("/?view=academic");
  await page.getByLabel("הסיסמה שלך").fill("lifeos automated test password");
  await page.getByRole("button",{name:"כניסה למרחב שלך"}).click();
  await expect(page.locator("#page-title")).toBeVisible();
  const session=await (await page.request.get("/api/session")).json();expect(session.test_mode).toBe(true);
  const headers={Origin:BASE,"X-CSRF-Token":session.csrf};
  async function create(kind:string,data:object) { const response=await page.request.post(`/api/academic/${kind}`,{headers,data});expect(response.ok()).toBe(true);return response.json(); }
  const today=dayKey(new Date(),"Asia/Jerusalem");
  const old=await create("terms",{name:"Earlier fixture term",start_date:shiftDay(today,-60),end_date:shiftDay(today,30)});
  const current=await create("terms",{name:"Selected fixture term",start_date:today,end_date:shiftDay(today,90)});
  await create("courses",{name:"Excluded course fixture",term_id:old.id});
  const course=await create("courses",{name:"Selected course fixture",term_id:current.id});
  await page.reload();
  await page.locator(".academic-scope > summary").click();
  await page.getByLabel("סינון לפי סמסטר",{exact:true}).selectOption(current.id);
  await page.locator(".academic-manual-tools > summary").click();
  await page.getByRole("button",{name:"קורס חדש",exact:true}).click();
  await expect(page.getByRole("dialog").getByLabel("סמסטר",{exact:true})).toHaveValue(current.id);
  await page.getByRole("button",{name:"סגירה",exact:true}).click();
  await page.getByRole("button",{name:"מטלה או מבחן חדש",exact:true}).click();
  const dialog=page.getByRole("dialog");
  await expect(dialog.getByLabel("קורס",{exact:true})).toHaveValue("");
  await expect(dialog.getByLabel("קורס",{exact:true}).getByRole("option")).toHaveCount(2);
  await dialog.getByLabel("כותרת",{exact:true}).fill("Quick captured fixture");
  await dialog.getByLabel("מועד",{exact:true}).fill(shiftDay(today,2));
  await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
  await expect(dialog).toBeVisible();
  expect(await (await page.request.get("/api/academic/items")).json()).toHaveLength(0);
  await dialog.getByLabel("קורס",{exact:true}).selectOption(course.id);
  await page.setViewportSize({width:320,height:740});
  expect(await dialog.evaluate(e=>e.scrollWidth<=e.clientWidth)).toBe(true);
  await page.route("**/api/academic/items",route=>route.fulfill({status:503,json:{detail:"academic_busy"}}),{times:1});
  await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
  await expect(dialog.getByRole("alert")).toBeVisible();
  await expect(dialog.getByText("מסד הנתונים עסוק. הניסיון הזה לא שמר דבר. המתינו מעט ונסו שוב.",{exact:true})).toBeVisible();
  await expect(dialog.getByLabel("קורס",{exact:true})).toHaveValue(course.id);
  await expect(dialog.getByLabel("כותרת",{exact:true})).toHaveValue("Quick captured fixture");
  await expect(dialog.getByLabel("מועד",{exact:true})).toHaveValue(shiftDay(today,2));
  await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("region",{name:"מטלות ומבחנים",exact:true}).getByText("Quick captured fixture",{exact:true})).toBeVisible();
  const items=await (await page.request.get("/api/academic/items")).json();
  expect(items).toHaveLength(1);expect(items[0]).toMatchObject({course_id:course.id,due:shiftDay(today,2)});
  expect(await (await page.request.get("/api/tasks")).json()).toHaveLength(1);
  await page.reload();
  await expect(page.getByRole("region",{name:"מטלות ומבחנים",exact:true}).getByText("Quick captured fixture",{exact:true})).toBeVisible();
});
