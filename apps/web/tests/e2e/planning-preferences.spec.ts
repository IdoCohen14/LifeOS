import { test, expect } from '@playwright/test';
import { BASE, prepareFixtures, openDashboardTool } from './helpers';
test.beforeEach(async ({ playwright }) => prepareFixtures(playwright));
test('saved preferences prefill new planning, allow overrides and reset explicitly', async ({ page }) => {
  await page.goto('/?view=settings');
  await page.getByLabel('הסיסמה שלך').fill('lifeos automated test password');
  await page.getByRole('button', { name: 'כניסה למרחב שלך' }).click();
  await page.locator('summary').getByText('העדפות תכנון', { exact: true }).click();
  await page.getByText('הצגה ועריכת העדפות', { exact: true }).click();
  await expect(page.getByLabel('שימוש בהעדפות בתכנון משימה')).not.toBeChecked();
  await page.getByLabel('שימוש בהעדפות בתכנון משימה').check();
  await page.getByLabel('משך מועדף בדקות').fill('45');
  await page.getByLabel('מספר ימי חיפוש מועדף').fill('3');
  await page.getByLabel('שעת התחלה מועדפת').fill('09:00');
  await page.getByLabel('שעת סיום מועדפת').fill('17:00');
  await page.getByRole('button', { name: 'שמירת העדפות', exact: true }).click();
  await expect(page.getByText('ההעדפות נשמרו.', { exact: false })).toBeVisible();
  const session = await (await page.request.get('/api/session')).json();
  expect(session.test_mode).toBe(true);
  const headers = { Origin: BASE, 'X-CSRF-Token': session.csrf };
  await page.request.post('/api/tasks', { headers, data: { title: 'Preference fixture task' } });
  await page.goto('/');
  await openDashboardTool(page, 'למצוא זמן למשימות');
  await page.getByRole('button', { name: 'מציאת משבצת זמן', exact: true }).click();
  await expect(page.getByLabel('משך בדקות', { exact: true })).toHaveValue('45');
  await expect(page.getByLabel('טווח חיפוש', { exact: true })).toHaveValue('3');
  await page.getByText('אפשרויות תכנון', { exact: true }).click();
  await expect(page.getByLabel('תחילת חלון התכנון')).toHaveValue('09:00');
  await page.getByLabel('משך בדקות', { exact: true }).fill('60');
  await expect(page.getByLabel('משך בדקות', { exact: true })).toHaveValue('60');
  expect((await (await page.request.get('/api/planning/preferences')).json()).duration).toBe(45);
  await page.getByRole('button', { name: 'סגירה', exact: true }).click();
  await page.goto('/?view=settings');
  await page.locator('summary').getByText('העדפות תכנון', { exact: true }).click();
  await page.getByText('הצגה ועריכת העדפות', { exact: true }).click();
  await expect(page.getByLabel('משך מועדף בדקות')).toHaveValue('45');
  const value = await (await page.request.get('/api/planning/preferences')).json();
  expect((await page.request.put('/api/planning/preferences', { headers, data: { ...value, duration: 50 } })).ok()).toBe(true);
  await page.getByRole('button', { name: 'שמירת העדפות', exact: true }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'ההעדפות השתנו במקום אחר' })).toBeVisible();
  await page.getByRole('button', { name: 'רענון העדפות', exact: true }).click();
  await expect(page.getByLabel('משך מועדף בדקות')).toHaveValue('50');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../../.runtime/screenshots/planning-preferences-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'איפוס העדפות', exact: true }).click();
  await page.getByRole('button', { name: 'אישור איפוס ההעדפות', exact: true }).click();
  await expect(page.getByLabel('משך מועדף בדקות')).toHaveValue('30');
  await expect(page.getByLabel('שימוש בהעדפות בתכנון משימה')).not.toBeChecked();
});
