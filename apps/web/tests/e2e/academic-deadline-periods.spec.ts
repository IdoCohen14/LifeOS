import { test, expect } from "@playwright/test";
import { BASE, prepareFixtures } from "./helpers";
import { dayKey, localInstant, shiftDay } from "../../lib/dates";
test.beforeEach(async({playwright})=>prepareFixtures(playwright));
test("deadline periods preserve date-only today and distinguish expired timed deadlines",async({page})=>{
 const today=dayKey(new Date(),"Asia/Jerusalem"),now=localInstant(`${today}T12:00`,"Asia/Jerusalem");
 await page.clock.install({time:new Date(now)});
 await page.goto("/?view=academic");
 await page.getByLabel("הסיסמה שלך").fill("lifeos automated test password");
 await page.getByRole("button",{name:"כניסה למרחב שלך"}).click();
 await expect(page.locator("#page-title")).toBeVisible();
 const session=await (await page.request.get("/api/session")).json();expect(session.test_mode).toBe(true);
 const headers={Origin:BASE,"X-CSRF-Token":session.csrf};
 async function create(kind:string,data:object){const response=await page.request.post(`/api/academic/${kind}`,{headers,data});expect(response.ok()).toBe(true);return response.json();}
 const term=await create("terms",{name:"Period term fixture",start_date:shiftDay(today,-30),end_date:shiftDay(today,90)});
 const course=await create("courses",{name:"Period course fixture",term_id:term.id});
 for(const [title,due] of [["Old date fixture",shiftDay(today,-1)],["Timed past fixture",new Date(Date.parse(now)-3600000).toISOString()],["Date-only today fixture",today],["Seventh date fixture",shiftDay(today,6)],["Eighth date fixture",shiftDay(today,7)]]) await create("items",{title,due,course_id:course.id,kind:"assignment"});
 const before=await (await page.request.get("/api/academic/items")).json();
 await page.reload();
 const region=page.getByRole("region",{name:"מטלות ומבחנים",exact:true});
 await region.locator(".simple-filters > summary").click();
 await region.getByLabel("טווח המועדים").selectOption("overdue");
 await expect(region.getByRole("listitem")).toHaveCount(2);
 await expect(region.getByText("Timed past fixture",{exact:true})).toBeVisible();
 await expect(region.getByText("Date-only today fixture",{exact:true})).toHaveCount(0);
 await region.getByLabel("טווח המועדים").selectOption("today");
 await expect(region.getByRole("listitem")).toHaveCount(2);
 await expect(region.getByText("Date-only today fixture",{exact:true})).toBeVisible();
 await region.getByLabel("טווח המועדים").selectOption("week");
 await expect(region.getByRole("listitem")).toHaveCount(3);
 await expect(region.getByText("Seventh date fixture",{exact:true})).toBeVisible();
 await expect(region.getByText("Eighth date fixture",{exact:true})).toHaveCount(0);
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(await (await page.request.get("/api/academic/items")).json()).toEqual(before);
 const settings=await (await page.request.get("/api/settings")).json();
 expect((await page.request.put("/api/settings",{headers,data:{...settings,language:"en",theme:"light"}})).ok()).toBe(true);
 await page.goto("/?view=academic");
 const english=page.getByRole("region",{name:"Assignments and exams",exact:true});
 await english.locator(".simple-filters > summary").click();
 await english.getByLabel("Deadline period").selectOption("today");
 await expect(english.getByRole("listitem")).toHaveCount(2);
 await expect(english.getByText("Asia/Jerusalem",{exact:true})).toBeVisible();
});
