import { test, expect } from "@playwright/test";
import { BASE, prepareFixtures } from "./helpers";
import { dayKey, shiftDay } from "../../lib/dates";
test.beforeEach(async ({playwright})=>prepareFixtures(playwright));
test("weekly overview creates a real session, filters terms and opens the course timetable",async({page})=>{
 await page.goto("/?view=academic");
 await page.getByLabel("הסיסמה שלך").fill("lifeos automated test password");
 await page.getByRole("button",{name:"כניסה למרחב שלך"}).click();
 await expect(page.locator("#page-title")).toBeVisible();
 const session=await (await page.request.get("/api/session")).json();expect(session.test_mode).toBe(true);
 const headers={Origin:BASE,"X-CSRF-Token":session.csrf};
 async function create(kind:string,data:object){const response=await page.request.post(`/api/academic/${kind}`,{headers,data});expect(response.ok()).toBe(true);return response.json();}
 const today=dayKey(new Date(),"Asia/Jerusalem");
 const term=await create("terms",{name:"Weekly term fixture",start_date:today,end_date:shiftDay(today,90)});
 const other=await create("terms",{name:"Other weekly term",start_date:today,end_date:shiftDay(today,90)});
 const course=await create("courses",{name:"Weekly course fixture",term_id:term.id});
 const excluded=await create("courses",{name:"Excluded weekly course",term_id:other.id});
 await create("timetable",{course_id:excluded.id,weekday:0,start_time:"07:00",end_time:"08:00",timezone:"UTC",location:"Excluded room"});
 await page.reload();
 await page.locator(".academic-scope > summary").click();
 await page.getByLabel("סינון לפי סמסטר",{exact:true}).selectOption(term.id);
 await page.locator('.academic-manual-tools > summary').click();
 await page.getByRole("button",{name:"מפגש שבועי חדש",exact:true}).click();
 const dialog=page.getByRole("dialog");
 await expect(dialog.getByLabel("קורס",{exact:true})).toHaveValue("");
 await dialog.getByLabel("קורס",{exact:true}).selectOption(course.id);
 await dialog.getByLabel("יום בשבוע",{exact:true}).selectOption("0");
 await dialog.getByLabel("שעת התחלה",{exact:true}).fill("09:00");
 await dialog.getByLabel("שעת סיום",{exact:true}).fill("11:00");
 await dialog.getByLabel("מיקום",{exact:true}).fill("Room 101 fixture");
 await dialog.getByRole("button",{name:"שמירה",exact:true}).click();
 await expect(dialog).toHaveCount(0);
 await page.locator(".section-fold").filter({has:page.locator(".academic-weekly")}).locator(":scope > summary").click();
 const weekly=page.getByRole("region",{name:"מערכת שעות שבועית",exact:true});
 await weekly.locator("summary").click();
 await expect(weekly.getByText("Room 101 fixture",{exact:true})).toBeVisible();
 await expect(weekly.getByText("Excluded room",{exact:true})).toHaveCount(0);
 await expect(weekly.getByText("Asia/Jerusalem",{exact:true})).toBeVisible();
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await weekly.screenshot({path:"../../.runtime/screenshots/academic-weekly-mobile.png"});
 await weekly.getByRole("button",{name:"פתיחת מערכת הקורס: Weekly course fixture"}).click();
 await expect(page.getByRole("tab",{name:"מערכת שעות",exact:true})).toHaveAttribute("aria-selected","true");
 await expect(page.getByText("Room 101 fixture",{exact:true})).toBeVisible();
 const settings=await (await page.request.get("/api/settings")).json();
 expect((await page.request.put("/api/settings",{headers,data:{...settings,language:"en",theme:"light"}})).ok()).toBe(true);
 await page.goto("/?view=academic");
 await page.locator(".section-fold").filter({has:page.locator(".academic-weekly")}).locator(":scope > summary").click();
 const english=page.getByRole("region",{name:"Weekly timetable",exact:true});
 await english.locator("summary").click();
 await expect(english.getByRole("region",{name:"Sunday",exact:true})).toBeVisible();
 await expect(english.getByText("Room 101 fixture",{exact:true})).toBeVisible();
 await expect(english.getByText("Excluded room",{exact:true})).toBeVisible();
});
