"""Bounded authenticated backups, scoped JSON export and offline-only recovery."""

import hashlib
import hmac
import io
import json
import os
import sqlite3
import tempfile
import time
import zipfile
from contextlib import closing, contextmanager
from datetime import datetime, timezone
from pathlib import Path
from uuid import uuid4

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from cryptography.fernet import Fernet
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.scrypt import Scrypt
from sqlalchemy import create_engine

from .data_lock import backup_lock, data_lock

MAGIC = b"LIFEOSBK1\n"
MAX_DATABASE = 128 * 1024 * 1024
MAX_PACKAGE = MAX_DATABASE + 128 * 1024
ALLOWED = {"manifest.json", "lifeos.sqlite3", "auth.json", "provider.key"}
MIGRATIONS = Path(__file__).resolve().parents[1] / "alembic"


class RecoveryError(Exception):
    pass


def utc_now():
    return datetime.now(timezone.utc).isoformat()


def validate_password(password):
    if not isinstance(password, str) or not 8 <= len(password) <= 1024:
        raise RecoveryError("backup_password_minimum_8")


def derive(password, salt):
    validate_password(password)
    return Scrypt(salt=salt, length=32, n=32768, r=8, p=1).derive(password.encode("utf-8"))


@contextmanager
def temporary_database(directory):
    directory = directory.resolve()
    directory.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix=".recovery-", suffix=".sqlite3", dir=directory)
    os.close(fd)
    path = Path(name).resolve()
    if path.parent != directory or not path.name.startswith(".recovery-"):
        raise RecoveryError("invalid_temporary_path")
    try:
        yield path
    finally:
        for suffix in ("", "-wal", "-shm", "-journal"):
            Path(str(path) + suffix).unlink(missing_ok=True)


def connect(path):
    connection = sqlite3.connect(str(path), timeout=5)
    started = time.monotonic()
    connection.set_progress_handler(lambda: int(time.monotonic() - started > 20), 10000)
    return connection


def schema_rows(db):
    rows = db.execute(
        "select type,name,tbl_name,sql from sqlite_master where sql is not null and name not like 'sqlite_%' order by type,name"
    ).fetchall()
    if len(rows) > 300 or any(len(row[3]) > 20000 for row in rows):
        raise RecoveryError("unsupported_backup_schema")
    return [(kind, name, table, " ".join(sql.split())) for kind, name, table, sql in rows]


def validate_database(path, directory, expected_revision=None):
    if path.stat().st_size > MAX_DATABASE:
        raise RecoveryError("backup_too_large")
    with closing(connect(path)) as db:
        if (
            db.execute("pragma integrity_check").fetchone()[0] != "ok"
            or db.execute("pragma foreign_key_check").fetchone()
        ):
            raise RecoveryError("database_integrity_failed")
        revision = db.execute("select version_num from alembic_version").fetchone()[0]
        known = {r.revision for r in ScriptDirectory(str(MIGRATIONS)).walk_revisions()}
        if revision not in known or (expected_revision and revision != expected_revision):
            raise RecoveryError("unsupported_backup_schema")
        actual_schema = schema_rows(db)
        counts = {
            table: db.execute(f'SELECT count(*) FROM "{table}"').fetchone()[0]
            for table in ("tasks", "events", "sessions")
        }
    # Only accept the actual schema generated by this app's migrations, not injected views/triggers.
    with temporary_database(directory) as expected_path:
        engine = create_engine("sqlite:///" + str(expected_path))
        try:
            cfg = Config()
            cfg.set_main_option("script_location", str(MIGRATIONS))
            with engine.begin() as connection:
                cfg.attributes["connection"] = connection
                command.upgrade(cfg, revision)
            with closing(connect(expected_path)) as expected:
                if schema_rows(expected) != actual_schema:
                    raise RecoveryError("unsupported_backup_schema")
        finally:
            engine.dispose()
    return {"schema": revision, "counts": counts}


def copy_database(source, target):
    started = time.monotonic()
    with closing(connect(source)) as original, closing(connect(target)) as backup:
        page_size = original.execute("pragma page_size").fetchone()[0]

        def progress(status, remaining, total):
            if total * page_size > MAX_DATABASE:
                raise RecoveryError("backup_too_large")
            if time.monotonic() - started > 30:
                raise RecoveryError("backup_timeout")

        original.backup(backup, pages=128, progress=progress, sleep=0.01)


@contextmanager
def snapshot(directory, sanitize=True):
    source = directory / "lifeos.sqlite3"
    if not source.is_file():
        raise RecoveryError("database_missing")
    with temporary_database(directory) as path:
        copy_database(source, path)
        with closing(connect(path)) as db:
            db.execute("pragma foreign_keys=on")
            db.execute("pragma journal_mode=delete")
            if sanitize:
                db.execute("pragma secure_delete=on")
                db.execute("delete from sessions")
                tables = {
                    row[0]
                    for row in db.execute("select name from sqlite_master where type='table'")
                }
                for push_table in ("push_deliveries", "push_devices", "push_config"):
                    if push_table in tables:
                        db.execute(f"delete from {push_table}")
                if "backup_schedule" in tables:
                    db.execute(
                        "update backup_schedule set enabled=0,encrypted_password=null,last_attempt=null,last_success=null,last_day=null,last_zone=null,last_error=null"
                    )
                for table in ("google_connection", "gmail_connection", "moodle_connection"):
                    if table in tables:
                        db.execute(f"update {table} set lease_owner=null,lease_until=0")
            db.commit()
        yield path


def metadata(path):
    return {
        "id": path.stem,
        "created_at": datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat(),
        "size": path.stat().st_size,
    }


def create_backup(directory, password):
    try:
        with backup_lock(Path(directory)):
            return _create_backup(directory, password)
    except RuntimeError:
        raise RecoveryError("backup_busy") from None


def _create_backup(directory, password):
    validate_password(password)
    directory = Path(directory).resolve()
    with snapshot(directory) as db_path:
        info = validate_database(db_path, directory)
        if (directory / "auth.json").stat().st_size > 4096:
            raise RecoveryError("invalid_backup_auth")
        auth = (directory / "auth.json").read_bytes()
        validate_auth(auth)
        entries = {
            "lifeos.sqlite3": db_path.read_bytes(),
            "auth.json": auth,
            "manifest.json": json.dumps(
                {
                    "format": "lifeos-backup",
                    "version": 1,
                    "created_at": utc_now(),
                    "schema": info["schema"],
                }
            ).encode(),
        }
        key_file = directory / "provider.key"
        if key_file.exists():
            if key_file.stat().st_size > 4096:
                raise RecoveryError("invalid_provider_key")
            key = key_file.read_bytes()
            Fernet(key)
            entries["provider.key"] = key
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", compression=zipfile.ZIP_STORED) as archive:
        for name, data in entries.items():
            archive.writestr(name, data)
    raw = buffer.getvalue()
    if len(raw) > MAX_PACKAGE:
        raise RecoveryError("backup_too_large")
    salt, nonce = os.urandom(16), os.urandom(12)
    header = MAGIC + salt + nonce
    encrypted = header + AESGCM(derive(password, salt)).encrypt(nonce, raw, header)
    folder = directory / "backups"
    folder.mkdir(exist_ok=True)
    target = folder / (str(uuid4()) + ".lifeosbackup")
    partial = target.with_suffix(".partial")
    try:
        with partial.open("xb") as file:
            os.chmod(partial, 0o600)
            file.write(encrypted)
            file.flush()
            os.fsync(file.fileno())
        os.replace(partial, target)
    finally:
        partial.unlink(missing_ok=True)
    return metadata(target)


def validate_auth(raw):
    try:
        if len(raw) > 4096:
            raise ValueError()
        auth = json.loads(raw)
        if (
            set(auth) != {"salt", "hash"}
            or len(bytes.fromhex(auth["salt"])) != 32
            or len(bytes.fromhex(auth["hash"])) != 64
        ):
            raise ValueError()
    except Exception:
        raise RecoveryError("invalid_backup_auth") from None


def unpack_backup(path, password, *, expected_sha256=None):
    path = Path(path)
    if path.stat().st_size > MAX_PACKAGE + 128:
        raise RecoveryError("backup_too_large")
    with path.open("rb") as source:
        data = source.read(MAX_PACKAGE + 129)
    if len(data) > MAX_PACKAGE + 128:
        raise RecoveryError("backup_too_large")
    if expected_sha256 is not None and not hmac.compare_digest(
        hashlib.sha256(data).hexdigest(), expected_sha256
    ):
        raise RecoveryError("backup_changed")
    if not data.startswith(MAGIC) or len(data) < len(MAGIC) + 44:
        raise RecoveryError("invalid_backup")
    offset = len(MAGIC)
    salt, nonce = data[offset : offset + 16], data[offset + 16 : offset + 28]
    try:
        raw = AESGCM(derive(password, salt)).decrypt(
            nonce, data[offset + 28 :], data[: offset + 28]
        )
    except Exception:
        raise RecoveryError("wrong_password_or_corrupt_backup") from None
    try:
        with zipfile.ZipFile(io.BytesIO(raw)) as archive:
            files = archive.infolist()
            names = [file.filename for file in files]
            if (
                len(names) != len(set(names))
                or not {"manifest.json", "lifeos.sqlite3", "auth.json"} <= set(names) <= ALLOWED
            ):
                raise ValueError()
            if (
                any(
                    file.compress_type != zipfile.ZIP_STORED or file.file_size > MAX_DATABASE
                    for file in files
                )
                or sum(file.file_size for file in files) > MAX_PACKAGE
            ):
                raise ValueError()
            entries = {name: archive.read(name) for name in names}
        manifest = json.loads(entries["manifest.json"])
        if (
            manifest.get("format") != "lifeos-backup"
            or manifest.get("version") != 1
            or not isinstance(manifest.get("schema"), str)
            or not isinstance(manifest.get("created_at"), str)
        ):
            raise ValueError()
        validate_auth(entries["auth.json"])
        if "provider.key" in entries:
            Fernet(entries["provider.key"])
        return entries, manifest
    except Exception:
        raise RecoveryError("invalid_backup") from None


def inspect_backup(path, password, *, expected_sha256=None):
    entries, manifest = unpack_backup(path, password, expected_sha256=expected_sha256)
    with temporary_database(Path(path).resolve().parent) as database:
        database.write_bytes(entries["lifeos.sqlite3"])
        return {
            **validate_database(database, database.parent, manifest["schema"]),
            "created_at": manifest["created_at"],
        }


def atomic_write(path, raw):
    temp = path.with_name(".recovery-" + str(uuid4()))
    try:
        with temp.open("xb") as file:
            os.chmod(temp, 0o600)
            file.write(raw)
            file.flush()
            os.fsync(file.fileno())
        os.replace(temp, path)
    finally:
        temp.unlink(missing_ok=True)


def restore_backup(path, password, directory, *, expected_sha256=None, authorize=None):
    directory = Path(directory).resolve()
    try:
        with data_lock(directory):
            entries, manifest = unpack_backup(path, password, expected_sha256=expected_sha256)
            with temporary_database(directory) as incoming:
                incoming.write_bytes(entries["lifeos.sqlite3"])
                info = validate_database(incoming, directory, manifest["schema"])
                target = directory / "lifeos.sqlite3"
                existed = target.exists()
                original_files = {
                    name: (directory / name).read_bytes() if (directory / name).exists() else None
                    for name in ("auth.json", "provider.key")
                }
                marker = directory / ".restore-in-progress"
                previous_marker = marker.read_bytes() if marker.exists() else None
                safety = create_backup(directory, password) if existed else None
                with temporary_database(directory) as rollback:
                    if existed:
                        copy_database(target, rollback)
                    try:
                        if authorize is not None:
                            authorize()
                        atomic_write(
                            marker,
                            json.dumps(
                                {"safety_backup_id": safety["id"] if safety else None}
                            ).encode(),
                        )
                        copy_database(incoming, target)
                        for name in ("auth.json", "provider.key"):
                            if name in entries:
                                atomic_write(directory / name, entries[name])
                            else:
                                (directory / name).unlink(missing_ok=True)
                        if authorize is not None:
                            authorize()
                        marker.unlink()
                    except BaseException as error:
                        if existed:
                            copy_database(rollback, target)
                        else:
                            target.unlink(missing_ok=True)
                        for name, raw in original_files.items():
                            if raw is None:
                                (directory / name).unlink(missing_ok=True)
                            else:
                                atomic_write(directory / name, raw)
                        if previous_marker is None:
                            marker.unlink(missing_ok=True)
                        else:
                            atomic_write(marker, previous_marker)
                        if not isinstance(error, Exception) or (
                            isinstance(error, RecoveryError)
                            and str(error) == "recovery_preview_expired"
                        ):
                            raise
                        raise RecoveryError("restore_failed_rolled_back") from None
                return {**info, "safety_backup_id": safety["id"] if safety else None}
    except RuntimeError:
        raise RecoveryError("close_lifeos_before_recovery") from None


def export_personal(directory):
    with snapshot(directory) as path, closing(connect(path)) as db:
        db.row_factory = sqlite3.Row
        settings = dict(
            db.execute(
                "select display_name,language,theme,timezone from settings where id=1"
            ).fetchone()
        )
        tasks = [
            dict(row)
            for row in db.execute(
                "select id,title,notes,priority,due,completed,created_at from tasks"
            )
        ]
        events = [
            dict(row)
            for row in db.execute("select id,title,notes,start,end,all_day,created_at from events")
        ]
    raw = json.dumps(
        {
            "format": "lifeos-personal-export",
            "version": 1,
            "created_at": utc_now(),
            "settings": settings,
            "tasks": tasks,
            "events": events,
        },
        ensure_ascii=False,
    ).encode("utf-8")
    if len(raw) > MAX_PACKAGE:
        raise RecoveryError("export_too_large")
    return raw
